"""Generate scripts/Checks20261123.lean: #print axioms for every public theorem
declared in the modules listed in extract_axiom_targets.MODULES."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_axiom_targets as ex

OUT = "D:/langtonsant/scripts/Checks20261123.lean"

imports = [ex.module_name(sub, name) for sub, name in ex.MODULES]

names = []
for sub, name in ex.MODULES:
    path = os.path.join(ex.ROOT, sub, name + ".lean")
    for full, line, private in ex.extract(path):
        if not private:
            names.append(full)

lines = []
lines.append("/- Axiom audit for the modules listed below.")
lines.append("   Generated by scripts/extract_axiom_targets.py + scripts/gen_checks.py.")
lines.append("   Every public theorem (not private, not def) gets a `#print axioms`.")
lines.append("   Allowed axioms: propext, Classical.choice, Quot.sound. -/")
lines.append("")
for m in imports:
    lines.append(f"import {m}")
lines.append("")
lines.append("-- All public theorems, in declaration order.")
for n in names:
    lines.append(f"#print axioms {n}")
lines.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))

print(f"wrote {OUT}: {len(imports)} imports, {len(names)} theorems")
